// Admin: companies, company users, read-only company mode. Manager: users (multi-role, password reset), cars, my company, own password. Viewer: read-only.
import { ADMIN, apiAs, BASE, createRunner, ensureSeed, MANAGER, uniq } from './lib.mjs'

export async function run() {
  await ensureSeed()
  const r = await createRunner('admin-users-cars')
  const { page, ok, shot, dialog } = r
  const u = uniq()
  const checkRole = (label) => dialog().locator('label', { hasText: label }).getByRole('checkbox')

  try {
    await r.login(ADMIN)
    await page.waitForURL('**/companies')
    await page.waitForSelector('table tbody tr:has-text("Тест Логістик")')
    await shot('01-companies-list')
    const nav = await page.locator('[data-slot=sidebar-menu-button]').allTextContents()
    ok('admin nav shows only companies', nav.length === 1 && nav[0].includes('Компанії'), nav.join(','))

    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector('[data-slot=dialog-content] [data-slot=field-error]')
    ok('company name required', true)
    await page.fill('#c-name', `Компанія ${u}`)
    await page.fill('#c-edrpou', '1' + u + '0')
    await page.fill('#c-email', 'not-an-email')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('company email validated', (await dialog().locator('[data-slot=field-error]').count()) >= 1)
    await page.fill('#c-email', `office${u}@test.ua`)
    await page.fill('#c-notes', 'Тестова компанія')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForURL(/\/companies\/\d+$/)
    await page.waitForSelector(`h1:has-text("Компанія ${u}")`)
    ok('company created with notes', (await page.textContent('body')).includes('Тестова компанія'), page.url())
    const newCompanyUrl = page.url()
    await shot('02-company-page')

    await page.getByRole('button', { name: 'Ключ НП' }).click()
    await dialog().waitFor()
    await page.fill('#np-key', 'not-a-valid-key')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('NP key format validated client-side', (await dialog().locator('[data-slot=field-error]').count()) === 1)
    await page.fill('#np-key', '0123456789abcdef0123456789abcdef')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(600)
    ok('company NP key configured', (await page.textContent('body')).includes('Ключ налаштовано'))

    // users tab: create a manager with two roles
    await page.getByRole('tab', { name: 'Користувачі' }).click()
    await page.waitForURL('**/companies/*?tab=users')
    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await checkRole('Менеджер').click()
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('at least one role required', (await dialog().textContent()).includes('хоча б одну роль'))
    await checkRole('Менеджер').click()
    await checkRole('Водій').click()
    await page.fill('#u-lastName', 'Новий')
    await page.fill('#u-firstName', 'Менеджер')
    await page.fill('#u-email', `m${u}@test.ua`)
    await page.fill('#u-password', 'short')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('user password min length validated', (await dialog().locator('[data-slot=field-error]').count()) >= 1)
    await page.fill('#u-password', 'manager123')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    const row = page.locator(`table tbody tr:has-text("m${u}@test.ua")`)
    await row.waitFor()
    ok('admin created user with two roles', (await row.textContent()).includes('Менеджер') && (await row.textContent()).includes('Водій'))
    await shot('03-company-users')

    await page.getByRole('button', { name: 'Деактивувати' }).click()
    await dialog().waitFor()
    await dialog().getByRole('button', { name: 'Деактивувати' }).click()
    await page.waitForSelector('h1:has-text("Деактивована")')
    ok('company deactivated', true)
    await page.getByRole('button', { name: 'Активувати', exact: true }).click()
    await page.waitForSelector('h1:has-text("Активна")')
    ok('company activated', true)

    // read-only company mode on the seeded company
    await page.goto(BASE + '/companies')
    await page.locator('table tbody tr:has-text("Тест Логістик")').click()
    await page.waitForURL(/\/companies\/\d+$/)
    await page.getByRole('button', { name: 'Відкрити компанію' }).click()
    await page.waitForURL('**/parcels')
    await page.waitForSelector('table tbody tr:has-text("PT")')
    const modeBody = await page.textContent('body')
    ok('company mode banner shown', modeBody.includes('Перегляд компанії «Тест Логістик»'))
    const navMode = await page.locator('[data-slot=sidebar-menu-button]').allTextContents()
    ok('company mode nav has company pages + companies', navMode.length === 8, navMode.join(','))
    ok('company mode hides add button', (await page.getByRole('link', { name: 'Додати' }).count()) === 0)
    ok('company mode hides row selection', (await page.locator('table thead').getByRole('checkbox').count()) === 0)
    await shot('04-admin-company-mode')
    await page.goto(BASE + '/trips')
    await page.waitForSelector('h1:has-text("Рейси")')
    ok('company mode trips page without add', (await page.getByRole('button', { name: 'Додати' }).count()) === 0)
    await page.goto(BASE + '/company')
    await page.waitForSelector('text=Тест Логістик')
    ok('company mode my-company read-only', (await page.getByRole('button', { name: 'Редагувати' }).count()) === 0)
    await page.getByRole('button', { name: 'Вийти з режиму' }).click()
    await page.waitForURL('**/companies')
    ok('exited company mode', !(await page.textContent('body')).includes('Перегляд компанії'))

    // ===== MANAGER =====
    await r.login(MANAGER)
    const navM = await page.locator('[data-slot=sidebar-menu-button]').allTextContents()
    ok('manager nav has 7 items', navM.length === 7, navM.join(','))

    await page.goto(BASE + '/users?size=100')
    await page.waitForSelector('table tbody tr:has-text("rep@test.ua")')
    await shot('05-users-list')
    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await checkRole('Менеджер').click()
    await checkRole('Представник').click()
    await page.fill('#u-lastName', 'Представник')
    await page.fill('#u-firstName', u)
    await page.fill('#u-email', `rep${u}@test.ua`)
    await page.fill('#u-password', 'rep12345')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    const phoneErr = await dialog().locator('[data-slot=field-error]').allTextContents()
    ok('representative phone required', phoneErr.some((e) => e.includes("Обов'язкове")), phoneErr.join(','))
    await page.fill('#u-phone', '38050' + u + '1')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    const repRow = page.locator(`table tbody tr:has-text("rep${u}@test.ua")`)
    await repRow.waitFor()
    ok('representative created', true)

    await repRow.getByRole('button', { name: 'Нова Пошта' }).click()
    await dialog().waitFor()
    await page.fill('#np-key', 'fedcba9876543210fedcba9876543210')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(600)
    ok('representative NP key saved', (await repRow.textContent()).includes('Ключ є'))

    // reset password, then log in as that user
    await repRow.getByRole('button', { name: 'Скинути пароль' }).click()
    await dialog().waitFor()
    await page.fill('#rp-password', 'newpass123')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector('text=Пароль скинуто')
    const repLogin = await fetch('http://localhost:8080/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: `rep${u}@test.ua`, password: 'newpass123' }) })
    ok('reset password works for login', repLogin.status === 200)

    // edit: add VIEWER role, deactivate
    await repRow.getByRole('button', { name: 'Редагувати' }).click()
    await dialog().waitFor()
    await checkRole('Перегляд').click()
    ok('roles change warning shown', (await dialog().textContent()).includes('розлогінено'))
    await dialog().getByRole('switch').click()
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(600)
    const repText = await repRow.textContent()
    ok('user roles updated and deactivated', repText.includes('Перегляд') && repText.includes('Деактивований'))
    await shot('06-user-edited')

    await page.click('[data-slot=select-trigger]')
    await page.locator('[data-slot=select-item]', { hasText: 'Водій' }).click()
    await page.waitForURL((u) => u.pathname.endsWith('/users') && u.searchParams.get('role') === 'DRIVER')
    ok('role filter in URL', true)

    // cars with notes
    await page.goto(BASE + '/cars')
    await page.waitForSelector('h1:has-text("Машини")')
    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await page.fill('#car-plate', 'AA' + u.slice(0, 4) + 'BB')
    await page.fill('#car-brand', 'Mercedes')
    await page.fill('#car-model', 'Sprinter')
    await page.fill('#car-capacity', 'abc')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('car capacity validated', (await dialog().locator('[data-slot=field-error]').count()) >= 1)
    await page.fill('#car-capacity', '1500')
    await page.fill('#car-volume', '12.5')
    await page.fill('#car-notes', 'Рефрижератор')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector(`table tbody tr:has-text("AA${u.slice(0, 4)}BB")`)
    ok('car created', true)
    await page.locator(`table tbody tr:has-text("AA${u.slice(0, 4)}BB")`).click()
    await dialog().waitFor()
    ok('car notes persisted', (await page.inputValue('#car-notes')) === 'Рефрижератор')
    await page.fill('#car-model', 'Sprinter 316')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector(`table tbody tr:has-text("AA${u.slice(0, 4)}BB"):has-text("Sprinter 316")`)
    ok('car edited', true)

    // my company + sync
    await page.goto(BASE + '/company')
    await page.waitForSelector('h1:has-text("Моя компанія")')
    await page.waitForSelector('text=Тест Логістик')
    await page.getByRole('button', { name: 'Синхронізувати з НП' }).click()
    await page.waitForTimeout(2500)
    ok('sync shows result or NP error', /Синхронізацію виконано|Імпортовано|Нової Пошти|Помилка/.test(await page.textContent('body')))

    // own password change for a throwaway manager (keeps the seeded manager password intact)
    const admin = await apiAs(ADMIN)
    const company = (await admin.get('/api/companies?size=100')).content.find((c) => c.name === 'Тест Логістик')
    const pwEmail = `pw${u}@test.ua`
    await admin.post('/api/users', { companyId: company.id, email: pwEmail, password: 'oldpass123', firstName: 'Пароль', lastName: u, roles: ['MANAGER'] })
    await r.login({ email: pwEmail, password: 'oldpass123' })
    await page.getByRole('button', { name: 'Змінити пароль' }).click()
    await dialog().waitFor()
    await page.fill('#cp-current', 'wrong')
    await page.fill('#cp-new', 'brandnew123')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(800)
    ok('wrong current password rejected', (await dialog().count()) === 1)
    await page.fill('#cp-current', 'oldpass123')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector('text=Пароль змінено')
    await page.goto(BASE + '/parcels')
    await page.waitForSelector('table tbody tr:has-text("PT")')
    ok('session continues with the new token after password change', !page.url().includes('/login'))
    const relogin = await fetch('http://localhost:8080/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: pwEmail, password: 'brandnew123' }) })
    ok('new password accepted by backend', relogin.status === 200)

    // ===== VIEWER =====
    const viewerEmail = `viewer${u}@test.ua`
    await admin.post('/api/users', { companyId: company.id, email: viewerEmail, password: 'viewer123', firstName: 'Переглядач', lastName: u, roles: ['VIEWER'] })
    await r.login({ email: viewerEmail, password: 'viewer123' })
    await page.waitForURL('**/parcels')
    await page.waitForSelector('table tbody tr:has-text("PT")')
    const vBody = await page.textContent('body')
    ok('viewer sees parcels with money column', vBody.includes('Оплата'))
    ok('viewer has no add/select controls', (await page.getByRole('link', { name: 'Додати' }).count()) === 0 && (await page.locator('table thead').getByRole('checkbox').count()) === 0)
    await page.locator('table tbody tr:has-text("PT")').first().click()
    await page.waitForSelector('h1:has-text("PT")')
    ok('viewer parcel page without edit/status', (await page.getByRole('button', { name: 'Редагувати' }).count()) === 0 && (await page.getByRole('button', { name: 'Змінити статус' }).count()) === 0)
    await shot('07-viewer')
    await page.goto(BASE + '/users?size=100')
    await page.waitForSelector('table tbody tr:has-text("rep@test.ua")')
    ok('viewer lists users without actions', (await page.getByRole('button', { name: 'Додати' }).count()) === 0)

    // ===== pure DRIVER → mobile-only page =====
    const driverEmail = `drv${u}@test.ua`
    await admin.post('/api/users', { companyId: company.id, email: driverEmail, password: 'driver123', firstName: 'Водій', lastName: u, roles: ['DRIVER'] })
    await r.login({ email: driverEmail, password: 'driver123' })
    await page.waitForURL('**/mobile-only')
    const mobileOnly = await page.getByText('мобільному застосунку').first().waitFor({ timeout: 5000 }).then(() => true, () => false)
    ok('pure driver lands on mobile-only page', mobileOnly)

    await r.login(ADMIN)
    await page.goto(BASE + '/users?size=100')
    await page.waitForTimeout(400)
    ok('admin outside company mode gets 403 on /users', (await page.textContent('body')).includes('403'))
    void newCompanyUrl
    return r.finish()
  } catch (e) {
    return r.finish(e)
  }
}

if (import.meta.url === `file://${process.argv[1]}`) process.exit((await run()) ? 0 : 1)
