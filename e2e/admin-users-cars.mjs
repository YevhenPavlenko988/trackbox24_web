// Phase 2: companies (admin), users, cars, my company.
import { ADMIN, BASE, createRunner, ensureSeed, MANAGER, uniq } from './lib.mjs'

export async function run() {
  await ensureSeed()
  const r = await createRunner('admin-users-cars')
  const { page, ok, shot, dialog } = r
  const u = uniq()

  try {
    await r.login(ADMIN)
    await page.waitForURL('**/companies')
    await page.waitForSelector('table tbody tr:has-text("Тест Логістик")')
    await shot('01-companies-list')
    const nav = await page.locator('[data-slot=sidebar-menu-button]').allTextContents()
    ok('admin nav shows only companies', nav.length === 1 && nav[0].includes('Компанії'), nav.join(','))

    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector('[data-slot=dialog-content] [data-slot=field-error]')
    ok('company name required', true)
    await page.fill('#c-name', `Компанія ${u}`)
    await page.fill('#c-edrpou', '1' + u + '0')
    await page.fill('#c-email', 'not-an-email')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('company email validated', (await dialog().locator('[data-slot=field-error]').count()) >= 1)
    await page.fill('#c-email', `office${u}@test.ua`)
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForURL(/\/companies\/\d+$/)
    await page.waitForSelector(`h1:has-text("Компанія ${u}")`)
    ok('company created and opened', true, page.url())
    await shot('02-company-page')

    await page.getByRole('button', { name: 'Редагувати' }).click()
    await dialog().waitFor()
    await page.fill('#c-address', 'вул. Тестова, 1')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(600)
    ok('company edit saved', (await page.textContent('body')).includes('вул. Тестова, 1'))

    await page.getByRole('button', { name: 'Ключ НП' }).click()
    await dialog().waitFor()
    await page.fill('#np-key', 'not-a-valid-key')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('NP key format validated client-side', (await dialog().locator('[data-slot=field-error]').count()) === 1)
    await page.fill('#np-key', '0123456789abcdef0123456789abcdef')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(600)
    ok('company NP key configured', (await page.textContent('body')).includes('Ключ налаштовано'))

    await page.getByRole('tab', { name: 'Користувачі' }).click()
    await page.waitForURL('**/companies/*?tab=users')
    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await page.fill('#u-lastName', 'Новий')
    await page.fill('#u-firstName', 'Менеджер')
    await page.fill('#u-email', `m${u}@test.ua`)
    await page.fill('#u-password', 'short')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('user password min length validated', (await dialog().locator('[data-slot=field-error]').count()) >= 1)
    await page.fill('#u-password', 'manager123')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector(`table tbody tr:has-text("m${u}@test.ua")`)
    ok('admin created manager in company', true)
    await shot('03-company-users')

    await page.getByRole('button', { name: 'Деактивувати' }).click()
    await dialog().waitFor()
    await dialog().getByRole('button', { name: 'Деактивувати' }).click()
    await page.waitForSelector('h1:has-text("Деактивована")')
    ok('company deactivated', true)
    await page.getByRole('button', { name: 'Активувати', exact: true }).click()
    await page.waitForSelector('h1:has-text("Активна")')
    ok('company activated', true)

    await r.login(MANAGER)
    const navM = await page.locator('[data-slot=sidebar-menu-button]').allTextContents()
    ok('manager nav has 7 items', navM.length === 7, navM.join(','))

    await page.goto(BASE + '/users')
    await page.waitForSelector('table tbody tr:has-text("rep@test.ua")')
    await shot('04-users-list')
    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await r.pickSelect('u-role', 'Представник')
    await page.fill('#u-lastName', 'Представник')
    await page.fill('#u-firstName', u)
    await page.fill('#u-email', `rep${u}@test.ua`)
    await page.fill('#u-password', 'rep12345')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    const phoneErr = await dialog().locator('[data-slot=field-error]').allTextContents()
    ok('representative phone required', phoneErr.some((e) => e.includes("Обов'язкове")), phoneErr.join(','))
    await page.fill('#u-phone', '38050' + u + '1')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector(`table tbody tr:has-text("rep${u}@test.ua")`)
    ok('representative created', true)

    const row = page.locator(`table tbody tr:has-text("rep${u}@test.ua")`)
    await row.getByRole('button', { name: 'Нова Пошта' }).click()
    await dialog().waitFor()
    await page.fill('#np-key', 'fedcba9876543210fedcba9876543210')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(600)
    ok('representative NP key saved', (await row.textContent()).includes('Ключ є'))
    await shot('05-user-np')

    await row.getByRole('button', { name: 'Редагувати' }).click()
    await dialog().waitFor()
    await dialog().getByRole('switch').click()
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(600)
    ok('user deactivated via edit', (await row.textContent()).includes('Деактивований'))

    await page.click('[data-slot=select-trigger]')
    await page.locator('[data-slot=select-item]', { hasText: 'Водій' }).click()
    await page.waitForURL('**/users?role=DRIVER')
    ok('role filter in URL', true)

    await page.goto(BASE + '/cars')
    await page.waitForSelector('h1:has-text("Машини")')
    await page.getByRole('button', { name: 'Додати' }).click()
    await dialog().waitFor()
    await page.fill('#car-plate', 'AA' + u.slice(0, 4) + 'BB')
    await page.fill('#car-brand', 'Mercedes')
    await page.fill('#car-model', 'Sprinter')
    await page.fill('#car-capacity', 'abc')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForTimeout(300)
    ok('car capacity validated', (await dialog().locator('[data-slot=field-error]').count()) >= 1)
    await page.fill('#car-capacity', '1500')
    await page.fill('#car-volume', '12.5')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector(`table tbody tr:has-text("AA${u.slice(0, 4)}BB")`)
    ok('car created', true)
    await shot('06-cars')
    await page.locator(`table tbody tr:has-text("AA${u.slice(0, 4)}BB")`).click()
    await dialog().waitFor()
    await page.fill('#car-model', 'Sprinter 316')
    await page.click('[data-slot=dialog-content] button[type=submit]')
    await page.waitForSelector(`table tbody tr:has-text("AA${u.slice(0, 4)}BB"):has-text("Sprinter 316")`)
    ok('car edited', true)

    await page.goto(BASE + '/company')
    await page.waitForSelector('h1:has-text("Моя компанія")')
    await page.waitForSelector('text=Тест Логістик')
    await shot('07-my-company')
    await page.getByRole('button', { name: 'Синхронізувати з НП' }).click()
    await page.waitForTimeout(2500)
    ok('sync shows result or NP error', /Синхронізацію виконано|Імпортовано|Нової Пошти|Помилка/.test(await page.textContent('body')))

    await r.login(ADMIN)
    await page.goto(BASE + '/users')
    await page.waitForTimeout(400)
    ok('admin gets 403 on /users', (await page.textContent('body')).includes('403'))
    return r.finish()
  } catch (e) {
    return r.finish(e)
  }
}

if (import.meta.url === `file://${process.argv[1]}`) process.exit((await run()) ? 0 : 1)
